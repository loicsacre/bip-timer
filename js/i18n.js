const LANGUAGE_KEY = 'bip-timer-language';

export const LANGUAGES = ['fr', 'en', 'nl'];

// English lives at the root, the address Google already ranks; the others have their own folder.
export const homePath = (code) => (code === 'en' ? '' : `${code}/`);

// The language of the last page used, or null for a first visit or blocked storage.
function savedLanguage() {
  try {
    const saved = localStorage.getItem(LANGUAGE_KEY);

    return STRINGS[saved] ? saved : null;
  } catch {
    return null;
  }
}

// The language last used wins; otherwise the first of the browser's languages we speak.
export function preferredLanguage() {
  const saved = savedLanguage();

  if (saved) {
    return saved;
  }

  const tags = typeof navigator === 'undefined' ? [] : (navigator.languages ?? [navigator.language]);

  for (const tag of tags) {
    const code = (tag ?? '').slice(0, 2).toLowerCase();

    if (STRINGS[code]) {
      return code;
    }
  }

  return 'en';
}

// Each language has its own page, so the page says which one it is; the page generator has none.
const pageLanguage = typeof document === 'undefined' ? 'en' : document.documentElement.lang;

export let lang = STRINGS[pageLanguage] ? pageLanguage : preferredLanguage();

export let t = STRINGS[lang];

export function setLanguage(code) {
  if (!STRINGS[code]) {
    return;
  }

  lang = code;
  t = STRINGS[code];

  try {
    localStorage.setItem(LANGUAGE_KEY, code);
  } catch {
    // The choice then lasts until the page is closed.
  }
}
